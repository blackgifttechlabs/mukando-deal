import assert from 'node:assert/strict';
import { cycleDate, buildRound, shuffled, paymentBalance, validatePayment, cycleMembers } from '../js/finance.js';
assert.equal(cycleDate('2026-01-31', 'monthly', 1), '2026-02-28');
assert.equal(cycleDate('2026-01-31', 'monthly', 2), '2026-03-31');
assert.equal(cycleDate('2024-01-31', 'monthly', 1), '2024-02-29');
assert.equal(cycleDate('2026-10-07', 'weekly', 2), '2026-10-21');
const members = ['m1', 'm2', 'm3'].map(id => ({ id, status: 'active', joinDate: '2026-01-01' }));
const rules = { clubName: 'Club', amount: 20, frequency: 'monthly', startDate: '2026-01-31', penaltyAmount: 2, graceDays: 3 };
const cycles = buildRound(members, rules, [], ['m2', 'm1', 'm3'], 'manual', 'log');
assert.deepEqual(cycles.map(cycle => cycle.recipientMemberId), ['m2', 'm1', 'm3']);
assert.deepEqual(cycles.map(cycle => cycle.status), ['open', 'scheduled', 'scheduled']);
assert.equal(cycles[0].expectedPoolCents, 6000);
assert.equal(cycleMembers(cycles[0], [...members, { id: 'outsider' }]).length, 3);
assert.throws(() => buildRound(members, rules, [], ['m1', 'm1', 'm3'], 'manual', 'log'));
assert.throws(() => buildRound(members, rules, cycles, ['m1', 'm2', 'm3'], 'manual', 'log'));
assert.deepEqual([...shuffled(['a', 'b', 'c'])].sort(), ['a', 'b', 'c']);
const cycle = cycles[0];
const partial = { id: 'p1', memberId: 'm1', cycleId: cycle.id, amount: 10, date: '2026-01-31' };
const rest = { ...partial, id: 'p2', amount: 10 };
assert.equal(paymentBalance(cycle, 'm1', [partial], '2026-02-01').status, 'Partial');
assert.equal(paymentBalance(cycle, 'm1', [partial, rest], '2026-02-05').status, 'Paid');
const reversal = { ...partial, id: 'rev', amount: -10, date: '2026-02-05', reversesPaymentId: 'p1' };
assert.equal(paymentBalance(cycle, 'm1', [partial, rest, reversal], '2026-02-05').outstanding, 12);
assert.equal(paymentBalance(cycle, 'm1', [], '2026-02-05').outstanding, 22);
assert.equal(validatePayment({ amount: '10.07', method: 'cash', reference: ' x ', date: '2026-01-31' }, cycle, members[0]).amountCents, 1007);
for (const amount of ['0', '-1', '1.999', '1000001']) assert.throws(() => validatePayment({ amount, method: 'cash', reference: '', date: '2026-01-31' }, cycle, members[0]));
assert.throws(() => validatePayment({ amount: '10', method: 'cash', reference: '', date: '2026-01-31' }, cycle, { id: 'outsider', joinDate: '2026-01-01' }));
console.log('PASS: anchored dates, complete rounds, expected pools, random order, membership, partial/full payments, penalties, reversals and payment validation.');
